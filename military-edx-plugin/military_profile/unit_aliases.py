# แปลงเลขไทย → อารบิก
_TH2AR = str.maketrans("๐๑๒๓๔๕๖๗๘๙", "0123456789")

# combined lookup (case-insensitive, normalized whitespace)
# maps ANY variant (abbr or alternate full) → canonical full name
_LOOKUP: dict[str, str] = {}
for abbr, full in _ABBR_TO_FULL.items():
    _LOOKUP[" ".join(abbr.split()).lower()] = full
for alias, canonical in _FULL_ALIASES.items():
    _LOOKUP[" ".join(alias.split()).lower()] = canonical
# canonical full names also point to themselves (idempotent)
for full in set(_ABBR_TO_FULL.values()) | set(_FULL_ALIASES.values()):
    _LOOKUP[" ".join(full.split()).lower()] = full


def normalize_unit(value: str) -> str:
    """
    Normalize a unit name to its canonical FULL name.

    - Abbreviation  → full name  (e.g. "มทบ.11" → "มณฑลทหารบกที่ 11")
    - Full name     → unchanged  (idempotent)
    - Unknown value → unchanged  (safe fallback)
    """
    if not value or not isinstance(value, str):
        return value or ""

    cleaned = " ".join(value.strip().split()).translate(_TH2AR)
    return _LOOKUP.get(cleaned.lower(), cleaned)
